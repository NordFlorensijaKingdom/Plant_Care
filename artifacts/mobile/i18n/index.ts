function interpolate(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    const v = params[key];
    return v == null ? "" : String(v);
  });
}

export function translate(language: Language, key: string, params?: Params): string {
  const fromLang = translations[language]?.[key];
  if (typeof fromLang === "string") return interpolate(fromLang, params);
  const fallback = translations.en[key];
  if (typeof fallback === "string") return interpolate(fallback, params);
  return key;
}

export function languageToLocale(language: Language): string {
  return language === "ru" ? "ru-RU" : "en-US";
}

export function useI18n(): { language: Language; locale: string; t: (key: string, params?: Params) => string } {
  const { language } = useAppSettings();
  const locale = useMemo(() => languageToLocale(language), [language]);
  const t = useCallback((key: string, params?: Params) => translate(language, key, params), [language]);
  return { language, locale, t };
}
